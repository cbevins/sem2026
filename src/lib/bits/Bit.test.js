import { describe, it, expect } from 'vitest';
import { Bit } from './Bit.js'

describe('Bit manipulation functions', () => {
    it('Bit.get() tests', () => {
        expect(0b10110001).toBe(177)
        expect(Bit.get(0b10110001, 0)).toBe(1)
        expect(Bit.get(0b10110001, 1)).toBe(0)
        expect(Bit.get(0b10110001, 2)).toBe(0)
        expect(Bit.get(0b10110001, 3)).toBe(0)
        expect(Bit.get(0b10110001, 4)).toBe(1)
        expect(Bit.get(0b10110001, 5)).toBe(1)
        expect(Bit.get(0b10110001, 6)).toBe(0)
        expect(Bit.get(0b10110001, 7)).toBe(1)
    })

    it('Bit.set() tests', () => {
		expect(0b10110000).toBe(176)
		expect(Bit.set(0b10110000, 1)).toBe(178)
        let byte = 0
        byte = Bit.set(byte, 0)
        expect(byte).toBe(1)
        byte = Bit.set(byte, 1)
        expect(byte).toBe(3)
        byte = Bit.set(byte, 2)
        expect(byte).toBe(7)
        byte = Bit.set(byte, 3)
        expect(byte).toBe(15)
        byte = Bit.set(byte, 4)
        expect(byte).toBe(31)
        byte = Bit.set(byte, 5)
        expect(byte).toBe(63)
        byte = Bit.set(byte, 6)
        expect(byte).toBe(127)
        byte = Bit.set(byte, 7)
        expect(byte).toBe(255)
        expect(Bit.set(0b00000000, 0)).toBe(0b00000001)
        expect(Bit.set(0b00000000, 1)).toBe(0b00000010)
        expect(Bit.set(0b00000000, 2)).toBe(0b00000100)
        expect(Bit.set(0b00000000, 3)).toBe(0b00001000)
        expect(Bit.set(0b00000000, 4)).toBe(0b00010000)
        expect(Bit.set(0b00000000, 5)).toBe(0b00100000)
        expect(Bit.set(0b00000000, 6)).toBe(0b01000000)
        expect(Bit.set(0b00000000, 7)).toBe(0b10000000)
	})

    it('Bit.clear() tests', () => {
        let byte = 255
        byte = Bit.clear(byte, 7)
        expect(byte).toBe(127)
        byte = Bit.clear(byte, 6)
        expect(byte).toBe(63)
        byte = Bit.clear(byte, 5)
        expect(byte).toBe(31)
        byte = Bit.clear(byte, 4)
        expect(byte).toBe(15)
        byte = Bit.clear(byte, 3)
        expect(byte).toBe(7)
        byte = Bit.clear(byte, 2)
        expect(byte).toBe(3)
        byte = Bit.clear(byte, 1)
        expect(byte).toBe(1)
        byte = Bit.clear(byte, 0)
        expect(byte).toBe(0)
        expect(Bit.clear(0b11111111, 0)).toBe(0b11111110)
        expect(Bit.clear(0b11111111, 1)).toBe(0b11111101)
        expect(Bit.clear(0b11111111, 2)).toBe(0b11111011)
        expect(Bit.clear(0b11111111, 3)).toBe(0b11110111)
        expect(Bit.clear(0b11111111, 4)).toBe(0b11101111)
        expect(Bit.clear(0b11111111, 5)).toBe(0b11011111)
        expect(Bit.clear(0b11111111, 6)).toBe(0b10111111)
        expect(Bit.clear(0b11111111, 7)).toBe(0b01111111)
	})

    it('Clear 4th bit of 10110000 (176) -> 10100000 (160)', () => {
		expect(0b10110000).toBe(176)
		expect(Bit.clear(0b10110000, 4)).toBe(160)
	})
})
